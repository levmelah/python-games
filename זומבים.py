def make_grime(base, tears=0, veins=False, seed=0):
    rnd = random.Random(seed)
    img = Image.new('RGB', (128, 128), base); d = ImageDraw.Draw(img)
    for _ in range(900):
        v = rnd.random()
        x, y = rnd.random() * 128, rnd.random() * 128
        c = tuple(max(0, min(255, int(ch * (0.8 + v * 0.35)))) for ch in base)
        d.rectangle([x, y, x + 2, y + 2], fill=c)
    for _ in range(8):
        x, y, r = rnd.random() * 128, rnd.random() * 128, 6 + rnd.random() * 16
        c = tuple(int(ch * 0.6) for ch in base)
        d.ellipse([x - r, y - r, x + r, y + r], fill=c)
    if veins:
        for _ in range(12):
            x, y = rnd.random() * 128, rnd.random() * 128; pts = [(x, y)]
            for _ in range(5):
                x += (rnd.random() - 0.5) * 20; y += (rnd.random() - 0.5) * 20; pts.append((x, y))
            d.line(pts, fill=(int(base[0] * 0.55), int(base[1] * 0.4), int(base[2] * 0.7)), width=1)
    for _ in range(tears):
        x, y = rnd.random() * 128, rnd.random() * 128
        d.polygon([(x + (rnd.random() - 0.3) * 22, y + (rnd.random() - 0.3) * 22) for _ in range(6)], fill=(125, 143, 90))
    img = img.filter(ImageFilter.GaussianBlur(0.6))
    return tex_from(img)


