SR = 22050


def _write_wav(name, samples):
    SND_DIR.mkdir(exist_ok=True)
    with wave.open(str(SND_DIR / f'{name}.wav'), 'w') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(b''.join(struct.pack('<h', int(max(-1, min(1, s)) * 30000)) for s in samples))


def _synth(dur, f1, f2, wave_type='sine', noise=0.0, vol=0.6, lowpass=1.0):
    n = int(SR * dur); out = []; ph = 0.0; last = 0.0
    for i in range(n):
        t = i / n
        f = f1 * (f2 / f1) ** t
        ph += f / SR
        if wave_type == 'sine': v = math.sin(ph * 2 * math.pi)
        elif wave_type == 'square': v = 1.0 if (ph % 1) < 0.5 else -1.0
        else: v = 2 * (ph % 1) - 1
        v = v * (1 - noise) + (random.random() * 2 - 1) * noise
        last = last + (v - last) * lowpass
        out.append(last * vol * (1 - t) ** 2)
    return out


