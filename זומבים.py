_LTR_RUN = re.compile(r'[A-Za-z0-9$%][A-Za-z0-9$%.,:+\-/]*(?: +[A-Za-z0-9$%][A-Za-z0-9$%.,:+\-/]*)*')
_MIRROR = str.maketrans('()[]<>', ')(][><')


def rtl(s):
    """turn logical Hebrew text into the visual order the text renderer needs"""
    out = []
    for line in s.split('\n'):
        r = line[::-1].translate(_MIRROR)
        r = _LTR_RUN.sub(lambda m: m.group(0)[::-1].translate(_MIRROR), r)
        out.append(r)
    return '\n'.join(out)


def T(he, en):
    return rtl(he) if HEB else en


