        meshes = zombie_meshes(ztype, vi)
        thin = 0.85 if ztype == 'runner' else 1.0
        bulk = 1.35 if ztype == 'brute' else 1.0
        eye_c = C('#b8ff5a') if ztype == 'spitter' else C('#ffd84a')
        tint = rng.uniform(0.9, 1.05)

        self.root = Entity()
        self.model = Entity(parent=self.root, scale=self.s, color=Color(tint, tint * rng.uniform(0.97, 1.03), tint, 1))
        m = self.model
        body = Entity(parent=m, y=0.9)
        hips = [Entity(parent=m, position=(sx * 0.11 * bulk, 0.9, 0)) for sx in (-1, 1)]
        knees = [Entity(parent=h, y=-0.46) for h in hips]
        shoulders = [Entity(parent=body, position=(sx * 0.27 * thin * bulk, 0.58, 0)) for sx in (-1, 1)]
        elbows = [Entity(parent=sh, y=-0.3) for sh in shoulders]
        head = Entity(parent=body, position=(0, 0.86, 0.03))
        jaw = Entity(parent=head, position=(0, -0.08, 0.02))
        joints = {'body': body, 'thigh_n': hips[0], 'thigh_p': hips[1], 'shin_n': knees[0], 'shin_p': knees[1],
                  'upperarm_n': shoulders[0], 'upperarm_p': shoulders[1], 'forearm_n': elbows[0], 'forearm_p': elbows[1],
                  'head': head, 'jaw': jaw}
        for name, joint in joints.items():
            mesh = meshes.get(name)
            if mesh is not None:
                mesh.copy_to(joint)
        # base pose
        body.rotation_x = 26 if ztype == 'runner' else 17
        body.rotation_z = rng.uniform(-5, 5)
        for sx, sh in zip((-1, 1), shoulders):
            sh.rotation = Vec3(-95, 0, sx * 7)
        self.body, self.hips, self.knees, self.shoulders, self.elbows, self.head, self.jaw = body, hips, knees, shoulders, elbows, head, jaw
