    def _init_state(self, ztype, rng, wave_n):
        T = self.T
        self.hp = T['hp']; self.dead = False; self.landed = False; self.gone = False
        self.speed = T['speed'] * (1 + min(0.5, wave_n * 0.03)) * rng.uniform(0.85, 1.15)
        self.target = 'player' if ztype == 'spitter' else ('vault' if rng.random() < 0.45 else 'player')
        self.walk = rng.random() * 6; self.atk_t = 0.5; self.swing = 0; self.spit_t = rng.uniform(1.5, 3.5)
        self.vel = Vec3(0, 0, 0); self.spin = Vec3(0, 0, 0); self.dead_t = 0; self.flash_t = 0
        self.stagger = 0.0; self.stag_dir = Vec3(0, 0, 0)
        self.last = Vec3(0, 0, 0); self.stuck = 0; self.side = rng.choice([-1, 1]); self.limp = rng.uniform(0.55, 1.0)

    @property
    def pos(self):
        return self.root.position

    def head_pos(self):
        return self.head.world_position

    def animate(self, dt, moving, t):
        amp = 48 if self.type == 'runner' else 29
        s0, s1 = math.sin(self.walk), -math.sin(self.walk)
        self.hips[0].rotation_x = s0 * amp
        self.hips[1].rotation_x = s1 * amp * self.limp
        self.knees[0].rotation_x = max(0, s0) * amp * 1.5
        self.knees[1].rotation_x = max(0, s1) * amp * 1.5 * self.limp + (1 - self.limp) * 14
        self.model.y = abs(math.cos(self.walk)) * 0.04 * (1 if moving else 0)
        if self.swing > 0:
            self.swing -= dt
        sw = math.sin((0.35 - self.swing) / 0.35 * math.pi) if self.swing > 0 else 0
        reach = 0.6 if self.type == 'spitter' else 1.0
        self.shoulders[0].rotation_x = (-95 + math.sin(self.walk * 0.5) * 8 - sw * 40) * reach
        self.shoulders[1].rotation_x = (-90 - math.sin(self.walk * 0.5 + 1) * 8 - sw * 40) * reach
        self.elbows[0].rotation_x = -14 - max(0, math.sin(t * 3 + self.walk)) * 14 + sw * 22
        self.elbows[1].rotation_x = -20 - max(0, math.sin(t * 3.3 + self.walk + 2)) * 14 + sw * 22
