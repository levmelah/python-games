def update_world(dt):
    # waves
    if G.wave == 0:
        G.break_t -= dt
        if G.break_t <= 0: start_wave()
    elif G.to_spawn == 0 and all(z.dead for z in G.zombies):
        if G.break_t > 0:
            G.break_t -= dt
            if G.break_t <= 0: start_wave()
        else:
            G.money += 1000; G.vault_hp = min(VAULT_MAX, G.vault_hp + 200); G.hp = 100
            banner(T(f'גל {G.wave} הושלם!', f'WAVE {G.wave} CLEARED!'), T('+$1,000 · הכספת תוקנה · הגל הבא בעוד רגע', '+$1,000   vault repaired   next wave soon'))
            snd('wave'); G.break_t = 5; place_barrels()
    if G.to_spawn > 0:
        G.spawn_t -= dt
        alive = sum(1 for z in G.zombies if not z.dead)
        if G.spawn_t <= 0 and alive < min(5 + G.wave, 14):
            spawn_zombie(); G.to_spawn -= 1; G.spawn_t = max(0.35, 1.0 - G.wave * 0.06)
    for g in door_glow:
        c = g.color; g.color = Color(c[0], c[1], c[2], max(0, c[3] - dt * 0.8))
    G.groan_t -= dt
    if G.groan_t <= 0:
        G.groan_t = random.uniform(0.8, 2.8)
        if any(not z.dead for z in G.zombies): snd('groan', 0.45)

    # zombies
    eye = Vec3(G.px, G.py + 1.4, G.pz)
    for z in G.zombies:
        p = z.root
        if z.dead:
            z.dead_t += dt
            if not z.landed:
                z.vel.y -= 18 * dt
                p.position += z.vel * dt
                p.rotation += z.spin * dt
                p.x, p.z = push_out(p.x, p.z, 0.3)
                if p.y <= 0.15 and z.vel.y < 0:
                    p.y = 0.15; z.vel = Vec3(0, 0, 0); p.rotation_x = -90; p.rotation_z = 0; z.landed = True
                    for _ in range(8): spawn_part(p.position, C('#888888'), 3, 0.4)
            if z.dead_t > 4:
                p.y -= dt * 0.5
                if z.dead_t > 6:
                    z.destroy(); z.gone = True
            continue
        dx, dz = G.px - p.x, G.pz - p.z
        d = math.hypot(dx, dz) or 0.001
        chase = z.target == 'player' or d < 6
        if z.stagger > 0:
            z.stagger -= dt
            p.x += z.stag_dir.x * 3.0 * dt; p.z += z.stag_dir.z * 3.0 * dt
            z.body.rotation_x = z.lean - 25 * min(1, z.stagger * 6)
            p.x, p.z = push_out(p.x, p.z, 0.42 * z.s)
            z.animate(dt, False, G.t)
            continue
        z.body.rotation_x += (z.lean - z.body.rotation_x) * min(1, dt * 8)
        vx, vz = max(-2.6, min(2.6, p.x)), -AZ + 1.25
        tx, tz = (G.px, G.pz) if chase else (vx, vz)
        gx, gz = tx - p.x, tz - p.z; gd = math.hypot(gx, gz) or 0.001
        reach = 1.05 + 0.35 * z.s if chase else 0.35
        moving = False
        if z.type == 'spitter' and chase:
            if d > 11:
                p.x += gx / gd * z.speed * dt; p.z += gz / gd * z.speed * dt; moving = True
            elif d < 7:
                p.x -= gx / gd * z.speed * dt; p.z -= gz / gd * z.speed * dt; moving = True
            z.spit_t -= dt
            if z.spit_t <= 0:
                mouth = z.head_pos() + Vec3(dx / d * 0.25, -0.05, dz / d * 0.25)
                tgt = Vec3(G.px, G.py + 1.3, G.pz)
                if clear_line(mouth, tgt):
                    aim = (tgt - mouth).normalized() + Vec3(random.uniform(-0.02, 0.02), 0, random.uniform(-0.02, 0.02))
                    spawn_bullet(mouth, aim, 'acid', 13); snd('acid', 0.6)
                    z.swing = 0.35; z.spit_t = random.uniform(2.2, 3.7)
                else:
                    z.spit_t = 0.5
        elif gd > reach:
            sx, sz = gx / gd, gz / gd
            if z.stuck > 0.6:
                sx += -gz / gd * z.side * 1.4; sz += gx / gd * z.side * 1.4
                l = math.hypot(sx, sz); sx /= l; sz /= l
                if z.stuck > 2:
                    z.stuck = 0; z.side *= -1
            p.x += sx * z.speed * dt; p.z += sz * z.speed * dt; moving = True
        else:
            z.atk_t -= dt
            if z.atk_t <= 0:
                z.atk_t = z.T['atk']; z.swing = 0.35
                hurt_player(z.T['dmg']) if chase else hurt_vault(z.T['vdmg'], p.x)
                if G.state != 'play': return
        p.rotation_y = math.degrees(math.atan2(dx, dz) if chase else math.atan2(gx, gz))
        p.x, p.z = push_out(p.x, p.z, 0.42 * z.s)
        for o in G.zombies:
            if o is z or o.dead: continue
            ox, oz = p.x - o.root.x, p.z - o.root.z; od = math.hypot(ox, oz); m = 0.45 * (z.s + o.s)
            if 0.001 < od < m:
                p.x += ox / od * (m - od) * 0.5; p.z += oz / od * (m - od) * 0.5
        prog = math.hypot(p.x - z.last.x, p.z - z.last.z)
        z.stuck = z.stuck + dt if (moving and prog < z.speed * dt * 0.3) else max(0, z.stuck - dt)
        z.last = Vec3(p.x, 0, p.z)
        if moving:
            z.walk += dt * (3 + z.speed * 1.6)
        z.animate(dt, moving, G.t)
    G.zombies = [z for z in G.zombies if not z.gone]

    # bullets
    for b in G.bullets:
        b['life'] -= dt
        if b['life'] <= 0:
            b['dead'] = True; continue
        e = b['e']; step = b['vel'].length() * dt; n = max(1, int(step / 0.3) + 1)
        for _ in range(n):
            if b.get('dead'): break
            e.position += b['vel'] * (dt / n); b['trav'] += step / n
            pos = e.position
            for br in G.barrels:
                if not br['dead'] and math.hypot(pos.x - br['x'], pos.z - br['z']) < 0.5 and pos.y < 1.2:
                    br['dead'] = True; b['dead'] = True; destroy(br['e']); explode(br['x'], 0.6, br['z']); break
            if b.get('dead'): break
            if blocked(pos.x, pos.y, pos.z):
                b['dead'] = True
                for _ in range(5): spawn_part(pos, C('#9ae6ff') if b['owner'] == 'player' else C('#b6ff5a'), 3, 0.3)
                break
            if b['owner'] == 'player':
                for z in G.zombies:
                    if z.dead: continue
                    h = hit_test(z, pos)
                    if h:
                        b['dead'] = True
                        damage_zombie(z, 150 if h == 'head' else 40, b['vel'], h == 'head')
                        for _ in range(7): spawn_part(pos, C('#7cff4a'), 3, 0.35)
                        break
            else:
                if math.hypot(pos.x - G.px, pos.z - G.pz) < 0.5 and G.py < pos.y < G.py + 1.85:
                    b['dead'] = True; hurt_player(10)
                    for _ in range(8): spawn_part(pos, C('#84ff3a'), 3, 0.4)
                    if G.state != 'play': return
    for b in G.bullets:
        if b.get('dead'): destroy(b['e'])
    G.bullets = [b for b in G.bullets if not b.get('dead')]

    # flying heads
    for f in G.flying:
        f['t'] += dt; e = f['e']
        if e.y > 0.12 or f['v'].y > 0:
            f['v'].y -= 18 * dt
            e.position += f['v'] * dt
            e.rotation += f['spin'] * dt
            if e.y <= 0.12 and f['v'].y < 0:
                e.y = 0.12; f['v'] = Vec3(f['v'].x * 0.4, abs(f['v'].y) * 0.35, f['v'].z * 0.4); f['spin'] *= 0.4
                if f['v'].y < 0.6: f['v'].y = 0
                splat(e.x, e.z, 0.5)
            e.x, e.z = push_out(e.x, e.z, 0.15)
        if f['t'] > 6:
            e.scale *= 0.96
        if f['t'] > 7:
            f['dead'] = True; destroy(e)
    G.flying = [f for f in G.flying if not f.get('dead')]

    # particles & explosions
    for p in G.parts:
        p['t'] += dt; p['v'].y -= 14 * dt; e = p['e']
        e.position += p['v'] * dt
        if e.y < 0.03:
            e.y = 0.03; p['v'] *= 0.5; p['v'].y *= -0.3
        e.scale = max(0.005, 0.07 * (1 - p['t'] / p['life']))
        if p['t'] > p['life']:
            p['dead'] = True; destroy(e)
    G.parts = [p for p in G.parts if not p.get('dead')]
    for b in G.booms:
        b['t'] += dt; k = b['t'] / 0.5
        b['e'].scale = 1 + k * 5; b['e'].color = Color(1, 0.7, 0.3, max(0, 0.9 * (1 - k)))
        if k >= 1:
            b['dead'] = True; destroy(b['e'])
    G.booms = [b for b in G.booms if not b.get('dead')]


