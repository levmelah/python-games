# procedural zombie art  (no Blender needed - everything is built here)
#   * smooth bodies from lathed profiles and deformed spheres
#   * per-vertex colours: mottled skin, bruises, veins, rot, dirt, blood
#   * torn clothes with real holes, ragged hems, accessories
#   * every body part is a separate mesh around its joint so it can move
# coordinates: y = up, z = forward (the zombie looks toward +z)
