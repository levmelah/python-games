def hit_test(z, p):
    if distance(p, z.head_pos()) < 0.21 * z.s:
        return 'head'
    if math.hypot(p.x - z.pos.x, p.z - z.pos.z) < 0.38 * z.s and 0 < p.y < 1.58 * z.s:
        return 'body'
    return None


def damage_zombie(z, dmg, direction, head):
    if z.dead: return
    z.hp -= dmg; z.flash_t = 0.08
