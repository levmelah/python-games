def _hash3(ix, iy, iz, seed):
    n = (ix * 374761393 + iy * 668265263 + iz * 2147483647 + seed * 144269) & 0xFFFFFFFF
    n = (n ^ (n >> 13)) * 1274126177 & 0xFFFFFFFF
    return ((n ^ (n >> 16)) & 0xFFFF) / 65535.0


def noise3(x, y, z, seed=0):
    ix, iy, iz = math.floor(x), math.floor(y), math.floor(z)
    fx, fy, fz = x - ix, y - iy, z - iz
    fx, fy, fz = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy), fz * fz * (3 - 2 * fz)
    h = _hash3
    x00 = h(ix, iy, iz, seed) + (h(ix + 1, iy, iz, seed) - h(ix, iy, iz, seed)) * fx
    x10 = h(ix, iy + 1, iz, seed) + (h(ix + 1, iy + 1, iz, seed) - h(ix, iy + 1, iz, seed)) * fx
    x01 = h(ix, iy, iz + 1, seed) + (h(ix + 1, iy, iz + 1, seed) - h(ix, iy, iz + 1, seed)) * fx
    x11 = h(ix, iy + 1, iz + 1, seed) + (h(ix + 1, iy + 1, iz + 1, seed) - h(ix, iy + 1, iz + 1, seed)) * fx
    y0 = x00 + (x10 - x00) * fy
    y1 = x01 + (x11 - x01) * fy
    return y0 + (y1 - y0) * fz


def fbm(p, scale, seed=0, octaves=3):
    v, a, f = 0.0, 0.5, scale
    for o in range(octaves):
        v += a * noise3(p[0] * f, p[1] * f, p[2] * f, seed + o * 17)
        a *= 0.5; f *= 2.1
    return v / 0.875


def hexc(h, k=1.0):
    h = h.lstrip('#')
    return tuple(min(1.0, int(h[i:i + 2], 16) / 255 * k) for i in (0, 2, 4))


def mixc(a, b, t):
    t = max(0.0, min(1.0, t))
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t)


# ---------- shape generators ----------
def g_lathe(rings, seg=20, cap_top=True, cap_bottom=True):
    """rings: (cx, cy, cz, rx, rz) from top to bottom, around the y axis"""
    verts, faces = [], []
    for (cx, cy, cz, rx, rz) in rings:
        for s in range(seg):
            a = s / seg * math.tau
            verts.append((cx + math.sin(a) * rx, cy, cz + math.cos(a) * rz))
    for r in range(len(rings) - 1):
        for s in range(seg):
            a = r * seg + s; b = r * seg + (s + 1) % seg
            faces.append((a + seg, b + seg, b, a))
    if cap_top:
        c = rings[0]; verts.append((c[0], c[1] + 0.003, c[2])); ci = len(verts) - 1
        for s in range(seg): faces.append((s, (s + 1) % seg, ci))
    if cap_bottom:
        c = rings[-1]; base = (len(rings) - 1) * seg; verts.append((c[0], c[1] - 0.003, c[2])); ci = len(verts) - 1
        for s in range(seg): faces.append((base + (s + 1) % seg, base + s, ci))
    return verts, faces


def g_limb(top, length, r0, r1, seg=16, bulge=0.0, flat=1.0, rings=10, wobble=0.0, seed=0):
    rr = []
    for i in range(rings):
        t = i / (rings - 1)
        r = r0 + (r1 - r0) * t + math.sin(t * math.pi) * bulge
        r += (noise3(t * 6, seed, 0, seed) - 0.5) * wobble
        # rounded ends
        if i == 0: r *= 0.75
        if i == rings - 1: r *= 0.8
        rr.append((top[0], top[1] - t * length, top[2], r, r * flat))
    return g_lathe(rr, seg)


def g_sphere(c, r, seg=24, rings=16, deform=None):
    verts, faces = [], []
    for i in range(rings + 1):
        th = i / rings * math.pi
        for s in range(seg):
            ph = s / seg * math.tau
            v = [math.sin(th) * math.sin(ph) * r[0], math.cos(th) * r[1], math.sin(th) * math.cos(ph) * r[2]]
            if deform: v = deform(v)
            verts.append((c[0] + v[0], c[1] + v[1], c[2] + v[2]))
    for i in range(rings):
        for s in range(seg):
            a = i * seg + s; b = i * seg + (s + 1) % seg
            faces.append((b, b + seg, a + seg, a))
    return verts, faces


def g_box(c, size, round_=0.0):
    x, y, z = size[0] / 2, size[1] / 2, size[2] / 2
    v = [(c[0] + sx * x, c[1] + sy * y, c[2] + sz * z) for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)]
    f = [(2, 3, 1, 0), (5, 7, 6, 4), (1, 5, 4, 0), (6, 7, 3, 2), (4, 6, 2, 0), (3, 7, 5, 1)]
    return v, f


def g_tube(points, radius, seg=8):
    """a bent tube through points [(x,y,z,r)...] (fingers, straps, drool)"""
    rings = []
    verts, faces = [], []
    for i, p in enumerate(points):
        nxt = points[min(i + 1, len(points) - 1)]; prv = points[max(i - 1, 0)]
        d = Vec3(nxt[0] - prv[0], nxt[1] - prv[1], nxt[2] - prv[2]).normalized()
        up = Vec3(0, 0, 1) if abs(d.y) > 0.9 else Vec3(0, 1, 0)
        u = d.cross(up).normalized(); w = d.cross(u).normalized()
        r = p[3] if len(p) > 3 else radius
        for s in range(seg):
            a = s / seg * math.tau
            o = u * math.cos(a) * r + w * math.sin(a) * r
            verts.append((p[0] + o.x, p[1] + o.y, p[2] + o.z))
    n = len(points)
    for i in range(n - 1):
        for s in range(seg):
            a = i * seg + s; b = i * seg + (s + 1) % seg
            faces.append((a, b, b + seg, a + seg))
    verts.append(points[0][:3]); c0 = len(verts) - 1
    verts.append(points[-1][:3]); c1 = len(verts) - 1
    for s in range(seg):
        faces.append(((s + 1) % seg, s, c0))
        base = (n - 1) * seg
        faces.append((base + s, base + (s + 1) % seg, c1))
    return verts, faces


# ---------- mesh assembly ----------
class PartMesh:
    """collects many pieces (with vertex colours) into one mesh around a pivot"""
    def __init__(self, pivot):
        self.pivot = pivot; self.v = []; self.t = []; self.c = []; self.n = []

    def add(self, vf, colfn, lumpy=0.0, holes=0.0, seed=0, flip=False):
        verts, faces = vf
        verts = [list(p) for p in verts]
        tris = []
        for f in faces:
            if holes and len(f) == 4:
                cx = sum(verts[i][0] for i in f) / 4; cy = sum(verts[i][1] for i in f) / 4; cz = sum(verts[i][2] for i in f) / 4
                if noise3(cx * 24, cy * 24, cz * 24, seed + 5) > 1 - holes:
                    continue
            for i in range(1, len(f) - 1):
                tris.append((f[0], f[i], f[i + 1]) if flip else (f[0], f[i + 1], f[i]))
        nrm = [[0.0, 0.0, 0.0] for _ in verts]
        for (a, b, c) in tris:
            ax, ay, az = verts[a]; bx, by, bz = verts[b]; cx, cy, cz = verts[c]
            ux, uy, uz = bx - ax, by - ay, bz - az; wx, wy, wz = cx - ax, cy - ay, cz - az
            nx, ny, nz = uy * wz - uz * wy, uz * wx - ux * wz, ux * wy - uy * wx
            for i in (a, b, c):
                nrm[i][0] += nx; nrm[i][1] += ny; nrm[i][2] += nz
        for i, n in enumerate(nrm):
            l = math.sqrt(n[0] ** 2 + n[1] ** 2 + n[2] ** 2) or 1
            nrm[i] = (n[0] / l, n[1] / l, n[2] / l)
        if lumpy:
            for i, p in enumerate(verts):
                d = (fbm(p, 14, seed) - 0.5) * lumpy
                p[0] += nrm[i][0] * d; p[1] += nrm[i][1] * d; p[2] += nrm[i][2] * d
        off = len(self.v)
        px, py, pz = self.pivot
        for i, p in enumerate(verts):
            self.v.append((p[0] - px, p[1] - py, p[2] - pz))
            self.n.append(nrm[i])
            col = colfn(p, nrm[i])
            self.c.append(Color(col[0], col[1], col[2], 1))
        for (a, b, c) in tris:
            self.t.extend((a + off, b + off, c + off))

    def build(self):
        if not self.v:
            return None
        return Mesh(vertices=self.v, triangles=self.t, colors=self.c, normals=self.n)


# ---------- colour functions ----------
def skin_fn(base, seed, rot=0.5):
    b = hexc(base)
    bruise = hexc('#4b2a4a'); rotc = hexc('#5a3a1a'); blood = hexc('#5c1414'); vein = hexc('#3d2656'); pale = hexc('#d9dcc0')
    def f(p, n):
        m = fbm(p, 9, seed)
        c = mixc(b, mixc(b, (0, 0, 0), 0.4), (m - 0.45) * 1.6)
        c = mixc(c, pale, (0.4 - m) * 0.8)
        br = fbm(p, 4, seed + 3)
        if br > 0.6: c = mixc(c, bruise, (br - 0.6) * 4)
        r = fbm(p, 6, seed + 9)
        if r > 1 - rot * 0.6: c = mixc(c, rotc, 0.6)
        if noise3(p[0] * 30, p[1] * 30, p[2] * 30, seed + 11) > 0.93: c = mixc(c, blood, 0.8)
        if abs(noise3(p[0] * 18, p[1] * 18, p[2] * 18, seed + 21) - 0.5) < 0.025: c = mixc(c, vein, 0.55)
        # light from above, darker underneath (cheap ambient occlusion)
        c = mixc(c, (0, 0, 0), max(0, -n[1]) * 0.28)
        return c
    return f


def cloth_fn(base, seed, dirt_below=0.5, weave=True):
    b = hexc(base)
    def f(p, n):
        m = fbm(p, 12, seed)
        c = mixc(b, (0, 0, 0), (m - 0.5) * 0.9)
        c = mixc(c, mixc(c, (1, 1, 1), 0.18), 0.45 - m)
        if weave and (math.floor(p[1] * 160) % 2 == 0):
            c = mixc(c, (0, 0, 0), 0.06)
        d = fbm(p, 5, seed + 2)
        if d > 0.58: c = mixc(c, hexc('#3b2a17'), (d - 0.58) * 3)
        if p[1] < dirt_below: c = mixc(c, hexc('#2a2015'), (dirt_below - p[1]) * 1.5)
        if noise3(p[0] * 25, p[1] * 25, p[2] * 25, seed + 8) > 0.94: c = mixc(c, hexc('#4a1010'), 0.7)
        c = mixc(c, (0, 0, 0), max(0, -n[1]) * 0.3)
        return c
    return f


def solid(h, shade=True):
    c = hexc(h)
    if not shade:
        return lambda p, n: c
    return lambda p, n: mixc(c, (0, 0, 0), max(0, -n[1]) * 0.3 + max(0, -n[2]) * 0.1)


def glowc(h):
    c = hexc(h)
    return lambda p, n: c


